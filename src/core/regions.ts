export function isRegionCode(code: unknown, allowWhole = false): code is RegionCode { return typeof code === 'string' && REGIONS.some(r => r.code === code && (allowWhole || !r.isWholePref)); }
export function expandRegions(codes: readonly RegionCode[]): RegionCode[] {
 return REGIONS.filter(r => !r.isWholePref && (codes.includes(r.code) || codes.some(code => REGIONS.some(w => w.code === code && w.isWholePref && w.pref === r.pref)))).map(r => r.code);
}
export function coversRegion(codes: readonly RegionCode[], target: RegionCode): boolean { return expandRegions(codes).includes(target); }
