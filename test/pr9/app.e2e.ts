async function open(page: Page) { await page.goto('/#partners'); await expect(page.getByRole('heading', { name: '事務所一覧', exact: true })).toBeVisible(); await expect(page.getByRole('table')).toBeVisible(); }
async function api(page: Page, path: string, body?: unknown, method = body ? 'POST' : 'GET') { const response = await page.request.fetch(`/api${path}`, { method, headers: { Origin: origin, 'Content-Type': 'application/json' }, ...(body ? { data: body } : {}) }); expect(response.ok(), `${method} ${path}: ${response.status()} ${response.ok() ? '' : await response.text()}`).toBeTruthy(); return (await response.json()).data; }
async function fixtureOffice(page: Page, code: string, fields: string[], changes: Record<string, unknown> = {}) { return api(page, '/partners', { website: '', code, shortName: '架空ブラウザ', fields, licenses: ['設備設計一級建築士'], experience: { '教育施設': { '新築': 0, '改修': 0 }, '公営住宅': { '新築': 0, '改修': 0 }, '公共施設': { '新築': 0, '改修': 0 } }, regions: ['13-all'], services: ['役所打合せ', '定例会出席', '現地調査', '平日電話対応', '納品検査出席', '積算'], capacity: 2, active: true, ...changes }); }
async function fixtureProject(page: Page, name: string, changes: Record<string, unknown> = {}) { return api(page, '/projects', { website: '', name, requiredFields: ['電気', '機械'], workType: '新築', use: '教育施設', region: '13101', floors: 2, floorArea: 5000, period: { start: '2027-01-01', end: '2027-03-31' }, requiredServices: [], orderType: '入札', requireListedLicense: false, ...changes }); }
async function confirm(page: Page) { await page.getByRole('button', { name: '確定して実行する', exact: true }).click(); }
