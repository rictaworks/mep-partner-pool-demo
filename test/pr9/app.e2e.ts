test('二つのブラウザで所有者分離・XSS文字列・keyboard・履歴と古い応答・障害', async ({ page, browser }) => {
    await open(page);
    const p = await fixtureOffice(page, 'ISOLATED', ['電気'], { shortName: '<img src=x onerror=alert(1)>' });
    await page.reload();
    await expect(page.getByText('ISOLATED / <img src=x onerror=alert(1)>', { exact: true })).toBeVisible();
    expect(await page.locator('main img').count()).toBe(0);
    const context = await browser.newContext();
    const other = await context.newPage();
    await open(other);
    await expect(other.getByText(/ISOLATED/)).toHaveCount(0);
    await other.goto(`/#partners/${p.id}`);
    await expect(other.getByRole('alert')).toContainText('対象が見つかりません。');
    await context.close();
    await page.getByRole('link', { name: '案件一覧', exact: true }).focus();
    await page.keyboard.press('Enter');
    await expect(page.getByRole('heading', { name: '案件一覧', exact: true })).toBeVisible();
    await page.goBack();
    await expect(page.getByRole('heading', { name: '事務所一覧', exact: true })).toBeVisible();
    await page.goForward();
    await expect(page.getByRole('heading', { name: '案件一覧', exact: true })).toBeVisible();
    await page.route('**/api/partners', async (route) => { await new Promise(resolve => setTimeout(resolve, 500)); try {
        await route.continue();
    }
    catch { /* navigation aborted an old read */ } });
    await page.getByRole('link', { name: '事務所一覧', exact: true }).click();
    await page.getByRole('link', { name: '案件一覧', exact: true }).click();
    await expect(page.getByRole('heading', { name: '案件一覧', exact: true })).toBeVisible();
    await page.waitForTimeout(700);
    await expect(page.getByRole('heading', { name: '案件一覧', exact: true })).toBeVisible();
    await page.unroute('**/api/partners');
    await page.route('**/api/projects', route => route.abort());
    await page.reload();
    await expect(page.getByRole('alert')).not.toBeEmpty();
    await page.unroute('**/api/projects');
    await page.getByRole('button', { name: '画面を再取得する' }).click();
    await expect(page.getByRole('heading', { name: '案件一覧', exact: true })).toBeVisible();
});
